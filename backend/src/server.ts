import express from 'express';
import cors from 'cors';
import helmet from 'helmet';
import morgan from 'morgan';
import rateLimit from 'express-rate-limit';
import { env } from './config/env.js';
import { requireAuth } from './middleware/auth.js';
import { errorHandler } from './middleware/errors.js';
import { api } from './routes/api.js';

const app=express();
app.disable('x-powered-by');
app.use(helmet());
app.use(cors({origin:env.FRONTEND_ORIGIN.split(',').map(s=>s.trim()),credentials:true}));
app.use(express.json({limit:'1mb'}));
app.use(morgan(env.NODE_ENV==='production'?'combined':'dev'));
app.get('/health',(_req,res)=>res.json({status:'ok',service:'knowflow-api',timestamp:new Date().toISOString()}));
app.use('/api',rateLimit({windowMs:60_000,limit:120,standardHeaders:'draft-7',legacyHeaders:false}),requireAuth,api);
app.use(errorHandler);
app.listen(env.PORT,()=>console.log(`KNOWFLOW API listening on ${env.PORT}`));
